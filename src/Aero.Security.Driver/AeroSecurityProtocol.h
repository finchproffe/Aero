#pragma once

#include <ntifs.h>

#define AERO_SECURITY_DEVICE_NT_NAME       L"\\Device\\AeroSecurity"
#define AERO_SECURITY_DEVICE_DOS_NAME      L"\\DosDevices\\AeroSecurity"

#define AERO_SECURITY_MAGIC                0x4F524541UL /* AERO */
#define AERO_SECURITY_PROTOCOL_VERSION     1UL

#define AERO_SECURITY_DRIVER_VERSION_MAJOR 0UL
#define AERO_SECURITY_DRIVER_VERSION_MINOR 4UL
#define AERO_SECURITY_DRIVER_VERSION_PATCH 0UL
#define AERO_SECURITY_DRIVER_VERSION_BUILD 1UL

#define AERO_SECURITY_CAPABILITY_PING                    0x00000001UL
#define AERO_SECURITY_CAPABILITY_VERSION                 0x00000002UL
#define AERO_SECURITY_CAPABILITY_PROCESS_PROTECTION      0x00000004UL
#define AERO_SECURITY_CAPABILITY_THREAD_PROTECTION       0x00000008UL
#define AERO_SECURITY_CAPABILITY_PROCESS_EXIT_TRACKING   0x00000010UL
#define AERO_SECURITY_CAPABILITY_PROTECTION_AUDIT        0x00000020UL

#define AERO_SECURITY_CAPABILITIES (                         \
    AERO_SECURITY_CAPABILITY_PING |                          \
    AERO_SECURITY_CAPABILITY_VERSION |                       \
    AERO_SECURITY_CAPABILITY_PROCESS_PROTECTION |            \
    AERO_SECURITY_CAPABILITY_THREAD_PROTECTION |             \
    AERO_SECURITY_CAPABILITY_PROCESS_EXIT_TRACKING |         \
    AERO_SECURITY_CAPABILITY_PROTECTION_AUDIT)

#define IOCTL_AERO_SECURITY_PING \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_AERO_SECURITY_GET_VERSION \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_AERO_SECURITY_PROTECT_CURRENT_PROCESS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_AERO_SECURITY_UNPROTECT_CURRENT_PROCESS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x803, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_AERO_SECURITY_GET_PROTECTION_STATUS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x804, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_AERO_SECURITY_GET_PROTECTION_STATUS_V2 \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x805, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#pragma pack(push, 8)

typedef struct _AERO_SECURITY_PING_REQUEST {
    ULONG Magic;
    ULONG ProtocolVersion;
    ULONGLONG Nonce;
} AERO_SECURITY_PING_REQUEST, *PAERO_SECURITY_PING_REQUEST;

typedef struct _AERO_SECURITY_PING_RESPONSE {
    ULONG Magic;
    ULONG ProtocolVersion;
    ULONGLONG Nonce;
    ULONG DriverVersionBuild;
    ULONG Capabilities;
} AERO_SECURITY_PING_RESPONSE, *PAERO_SECURITY_PING_RESPONSE;

typedef struct _AERO_SECURITY_VERSION_RESPONSE {
    ULONG Magic;
    ULONG ProtocolVersion;
    ULONG Major;
    ULONG Minor;
    ULONG Patch;
    ULONG Build;
    ULONG Capabilities;
    ULONG IsDebugBuild;
} AERO_SECURITY_VERSION_RESPONSE, *PAERO_SECURITY_VERSION_RESPONSE;

typedef struct _AERO_SECURITY_PROCESS_PROTECTION_REQUEST {
    ULONG Magic;
    ULONG ProtocolVersion;
    ULONGLONG ProcessId;
} AERO_SECURITY_PROCESS_PROTECTION_REQUEST,
  *PAERO_SECURITY_PROCESS_PROTECTION_REQUEST;

typedef struct _AERO_SECURITY_PROCESS_PROTECTION_STATUS {
    ULONG Magic;
    ULONG ProtocolVersion;
    ULONGLONG ProcessId;
    ULONG Active;
    ULONG BlockedAccessMask;
} AERO_SECURITY_PROCESS_PROTECTION_STATUS,
  *PAERO_SECURITY_PROCESS_PROTECTION_STATUS;

typedef struct _AERO_SECURITY_PROCESS_PROTECTION_STATUS_V2 {
    ULONG Magic;
    ULONG ProtocolVersion;
    ULONGLONG ProcessId;
    ULONG Active;
    ULONG Generation;
    ULONG BlockedProcessAccessMask;
    ULONG BlockedThreadAccessMask;
    ULONGLONG ProcessHandleDowngrades;
    ULONGLONG ThreadHandleDowngrades;
} AERO_SECURITY_PROCESS_PROTECTION_STATUS_V2,
  *PAERO_SECURITY_PROCESS_PROTECTION_STATUS_V2;

#pragma pack(pop)

C_ASSERT(sizeof(AERO_SECURITY_PING_REQUEST) == 16);
C_ASSERT(sizeof(AERO_SECURITY_PING_RESPONSE) == 24);
C_ASSERT(sizeof(AERO_SECURITY_VERSION_RESPONSE) == 32);
C_ASSERT(sizeof(AERO_SECURITY_PROCESS_PROTECTION_REQUEST) == 16);
C_ASSERT(sizeof(AERO_SECURITY_PROCESS_PROTECTION_STATUS) == 24);
C_ASSERT(sizeof(AERO_SECURITY_PROCESS_PROTECTION_STATUS_V2) == 48);
